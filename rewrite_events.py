def update_event(event, rewrite):
    """Update only title, description, and choices text/result_text."""
    event["title"] = rewrite["title"]
    event["description"] = rewrite["description"]

    new_choices = rewrite["choices"]
    original_choices = event.get("choices", [])

    if len(new_choices) != len(original_choices):
        print(f"  WARNING: {event['id']} choice count mismatch: "
              f"original={len(original_choices)}, new={len(new_choices)}")

    for i, (orig, new) in enumerate(zip(original_choices, new_choices)):
        orig["text"] = new["text"]
        orig["result_text"] = new["result_text"]

    return event


def process_file(fpath, target_ids):
    with open(fpath, "r", encoding="utf-8") as f:
        data = json.load(f)

    updated = 0
    for event in data:
        eid = event.get("id")
        if eid in target_ids and eid in REWRITES:
            print(f"  Updating: {eid}")
            update_event(event, REWRITES[eid])
            updated += 1

    with open(fpath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    return updated


