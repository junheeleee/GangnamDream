updated = []
for event_id, updates in enhancements.items():
    for i, e in enumerate(arc):
        if e["id"] == event_id:
            for key, val in updates.items():
                if key == "choices":
                    # 기존 choices의 effects/flags/follow_up_event 보존, text/result_text만 교체
                    orig = arc[i].get("choices", [])
                    merged = []
                    for j, new_ch in enumerate(val):
                        if j < len(orig):
                            ch = dict(orig[j])
                            if "text" in new_ch:
                                ch["text"] = new_ch["text"]
                            if "result_text" in new_ch:
                                ch["result_text"] = new_ch["result_text"]
                            if "effects" in new_ch:
                                ch["effects"] = {**ch.get("effects", {}), **new_ch["effects"]}
                            if "flags" in new_ch:
                                ch["flags"] = list(set(ch.get("flags", []) + new_ch["flags"]))
                        else:
                            ch = new_ch
                        merged.append(ch)
                    arc[i]["choices"] = merged
                else:
                    arc[i][key] = val
            updated.append(event_id)
            break

